#!/usr/bin/env python3
"""Regenerate meshmon/constants.py (hardware models and device roles) from the Meshtastic protobuf definitions.

Usage: python3 tools/update_constants.py [--ref master]
"""

import argparse
import os
import re
import urllib.request
from datetime import date

RAW = "https://raw.githubusercontent.com/meshtastic/protobufs/{ref}/meshtastic/{name}.proto"
OUT = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "meshmon", "constants.py")


def fetch(ref: str, name: str) -> str:
    with urllib.request.urlopen(RAW.format(ref=ref, name=name), timeout=30) as response:
        return response.read().decode("utf-8")


def parse_enum(text: str, name: str) -> dict:
    """Values of `enum <name> { ... }`, skipping nested braces such as option blocks"""
    start = text.index("{", re.search(rf"\benum\s+{name}\b", text).end())
    depth, i = 0, start
    while True:
        depth += (text[i] == "{") - (text[i] == "}")
        if depth == 0:
            break
        i += 1
    body = text[start + 1 : i]
    # drop nested option blocks and comments so only `NAME = number` lines remain
    body = re.sub(r"\[[^\]]*\]", "", body, flags=re.S)
    body = re.sub(r"//.*", "", body)
    return {int(num): label for label, num in re.findall(r"\b([A-Z][A-Z0-9_]*)\s*=\s*(\d+)", body)}


def render(name: str, values: dict) -> str:
    lines = [f"{name} = {{"] + [f'    {number}: "{label}",' for number, label in sorted(values.items())] + ["}"]
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--ref", default="master", help="git ref of meshtastic/protobufs (default: master)")
    args = parser.parse_args()

    hardware = parse_enum(fetch(args.ref, "mesh"), "HardwareModel")
    roles = parse_enum(fetch(args.ref, "config"), "Role")
    with open(OUT, "w", encoding="utf-8") as file:
        file.write(
            '"""Static Meshtastic lookup tables.\n\n'
            f"Generated by tools/update_constants.py from meshtastic/protobufs@{args.ref} on {date.today()};\n"
            'run that script to refresh them. Unknown numbers are shown as "HW-<n>" / "ROLE-<n>" by the UI.\n"""\n\n'
            f"# Config.DeviceConfig.Role\n{render('ROLES', roles)}\n\n"
            f"# HardwareModel (taken from meshtastic/protobufs, see also github.com/liamcottle/meshtastic-map)\n{render('HARDWARE', hardware)}\n"
        )
    print(f"Wrote {OUT}: {len(roles)} roles, {len(hardware)} hardware models")


if __name__ == "__main__":
    main()
